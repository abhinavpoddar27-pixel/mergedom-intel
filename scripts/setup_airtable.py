# ── Schema definitions ───────────────────────────────────────────────────────
# Each entry is (table_name, description, list_of_field_dicts).
# Field dicts follow the Airtable field model:
#   https://airtable.com/developers/web/api/field-model

_FIELD_TEXT = "singleLineText"
_FIELD_LONG = "multilineText"
_FIELD_NUM = "number"
_FIELD_DATE = "date"
_FIELD_DT = "dateTime"
_FIELD_CHECK = "checkbox"


def _text(name: str) -> dict:
    return {"name": name, "type": _FIELD_TEXT}


def _long(name: str) -> dict:
    return {"name": name, "type": _FIELD_LONG}


def _num(name: str, precision: int = 4) -> dict:
    return {
        "name": name,
        "type": _FIELD_NUM,
        "options": {"precision": precision},
    }


def _date(name: str) -> dict:
    return {
        "name": name,
        "type": _FIELD_DATE,
        "options": {"dateFormat": {"name": "iso"}},
    }


def _datetime(name: str) -> dict:
    return {
        "name": name,
        "type": _FIELD_DT,
        "options": {
            "dateFormat": {"name": "iso"},
            "timeFormat": {"name": "24hour"},
            "timeZone": "utc",
        },
    }


def _checkbox(name: str) -> dict:
    return {
        "name": name,
        "type": _FIELD_CHECK,
        "options": {"icon": "check", "color": "greenBright"},
    }


