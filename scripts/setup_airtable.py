# ── Main logic ───────────────────────────────────────────────────────────────

def main() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s  %(levelname)-8s  %(message)s",
    )

    cfg = get_settings()
    api_key = cfg.airtable_api_key
    base_id = cfg.airtable_base_id

    if not api_key or not base_id:
        print("ERROR: Set AIRTABLE_API_KEY and AIRTABLE_BASE_ID in .env")
        sys.exit(1)

    api = Api(api_key)
    print(f"Connecting to Airtable base {base_id} …")

    # ── Discover existing tables ──────────────────────────────────────────
    try:
        base = api.base(base_id, validate=True)
        schema = base.schema()
        existing = {t.name for t in schema.tables}
        print(f"Base contains {len(existing)} table(s): {sorted(existing)}")
    except Exception as exc:
        print(f"Failed to connect to base: {exc}")
        print()
        _print_manual_instructions()
        sys.exit(1)

    # ── Create missing tables ─────────────────────────────────────────────
    required = {name for name, _, _ in TABLE_SCHEMAS}
    missing = required - existing
    already = required & existing

    if already:
        print(f"\nAlready exist ({len(already)}):")
        for name in sorted(already):
            print(f"  ✓ {name}")

    if not missing:
        print("\nAll 10 tables are present — nothing to create.")
        return

    print(f"\nMissing ({len(missing)}):")
    for name in sorted(missing):
        print(f"  ✗ {name}")

    print("\nCreating missing tables …")
    created = 0
    failed: list[tuple[str, str]] = []

    for table_name, description, fields in TABLE_SCHEMAS:
        if table_name not in missing:
            continue
        try:
            base.create_table(table_name, fields=fields, description=description)
            print(f"  ✓ Created: {table_name}")
            created += 1
        except Exception as exc:
            err = str(exc)
            print(f"  ✗ Failed:  {table_name} — {err}")
            failed.append((table_name, err))

    print(f"\nDone: {created} created, {len(failed)} failed.")

    if failed:
        print("\nSome tables could not be created automatically.")
        _print_manual_instructions(only=failed)


def _print_manual_instructions(
    only: list[tuple[str, str]] | None = None,
) -> None:
    """Print step-by-step manual creation guide."""
    print("\n" + "=" * 60)
    print("MANUAL TABLE CREATION GUIDE")
    print("=" * 60)
    print()
    print("If the Airtable API cannot create tables (permission or plan")
    print("limits), create them manually in the Airtable web UI:")
    print()
    print("  1. Open https://airtable.com and navigate to your base.")
    print("  2. For each table listed below, click '+' to add a new table.")
    print("  3. Name it exactly as shown (case-sensitive).")
    print("  4. Add the fields with the types indicated.")
    print()

    tables = (
        [(name, err) for name, err in only]
        if only
        else [(name, "") for name, _, _ in TABLE_SCHEMAS]
    )
    for table_name, _ in tables:
        # Find matching schema
        for name, desc, fields in TABLE_SCHEMAS:
            if name == table_name:
                print(f"  TABLE: {name}")
                print(f"    {desc}")
                for fld in fields:
                    ftype = fld["type"]
                    readable = {
                        "singleLineText": "text",
                        "multilineText": "long text",
                        "number": "number",
                        "date": "date",
                        "dateTime": "datetime",
                        "checkbox": "checkbox",
                    }.get(ftype, ftype)
                    print(f"      • {fld['name']:25s} ({readable})")
                print()
                break


if __name__ == "__main__":
    main()
